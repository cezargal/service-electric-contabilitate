create table if not exists public.registru_inventar (
  id bigint generated by default as identity primary key,
  cui_entitate text not null default '43594993',
  exercitiu integer not null check (exercitiu between 2000 and 2100),
  data_inventar date not null,
  categorie text not null check (categorie in ('stocuri','obiecte_inventar','mijloace_fixe','disponibilitati','creante','datorii','altele')),
  denumire text not null check (length(trim(denumire)) > 0),
  valoare numeric(14,2) not null check (valoare >= 0),
  observatii text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists registru_inventar_exercitiu_idx on public.registru_inventar(exercitiu,data_inventar,id);
alter table public.registru_inventar enable row level security;
grant select,insert,update,delete on public.registru_inventar to authenticated;
grant usage,select on sequence public.registru_inventar_id_seq to authenticated;
drop policy if exists registru_inventar_admin_all on public.registru_inventar;
create policy registru_inventar_admin_all on public.registru_inventar
  for all to authenticated using (is_staff_admin()) with check (is_staff_admin());
