create table if not exists public.receptii_stoc (
  id bigint generated by default as identity primary key,
  cui_entitate text not null default '43594993',
  anaf_message_id text not null,
  anaf_cif text not null,
  invoice_series text,
  invoice_number text,
  invoice_date date,
  supplier_name text,
  supplier_cif text,
  line_index integer not null,
  product_name text not null,
  product_code text,
  measuring_unit text,
  categorie text not null default 'material' check (categorie in ('material','consumabil')),
  quantity numeric(12,3) not null check (quantity > 0),
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  purchase_date date not null default current_date,
  location text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint receptii_stoc_source_line_unique unique (anaf_cif,anaf_message_id,line_index)
);

create index if not exists receptii_stoc_product_idx on public.receptii_stoc(product_name);
create index if not exists receptii_stoc_purchase_date_idx on public.receptii_stoc(purchase_date);
create index if not exists receptii_stoc_invoice_idx on public.receptii_stoc(anaf_cif,anaf_message_id);

alter table public.receptii_stoc enable row level security;
grant select,insert,update,delete on public.receptii_stoc to authenticated;
grant usage,select on sequence public.receptii_stoc_id_seq to authenticated;
drop policy if exists receptii_stoc_admin_all on public.receptii_stoc;
create policy receptii_stoc_admin_all on public.receptii_stoc
  for all to authenticated using (is_staff_admin()) with check (is_staff_admin());
