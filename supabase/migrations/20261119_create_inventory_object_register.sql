create table if not exists public.obiecte_inventar (
  id bigint generated by default as identity primary key,
  cui_entitate text not null default '43594993',
  anaf_message_id text not null,
  anaf_cif text not null,
  invoice_series text,
  invoice_number text,
  invoice_date date,
  supplier_name text,
  supplier_cif text,
  line_index integer not null,
  product_name text not null,
  product_code text,
  measuring_unit text,
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
  purchase_date date not null default current_date,
  inventory_number text,
  serial_number text,
  status text not null default 'in_stoc'
    check (status in ('in_stoc','in_folosinta','scos_din_uz','casat')),
  date_put_into_use date,
  assigned_to text,
  location text,
  date_retired date,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint obiecte_inventar_source_number_unique unique (anaf_cif,anaf_message_id,line_index,inventory_number)
);

create index if not exists obiecte_inventar_status_idx on public.obiecte_inventar(status);
create index if not exists obiecte_inventar_purchase_date_idx on public.obiecte_inventar(purchase_date);
create index if not exists obiecte_inventar_invoice_idx on public.obiecte_inventar(anaf_cif,anaf_message_id);

alter table public.obiecte_inventar enable row level security;
grant select,insert,update,delete on public.obiecte_inventar to authenticated;
grant usage,select on sequence public.obiecte_inventar_id_seq to authenticated;
drop policy if exists obiecte_inventar_admin_all on public.obiecte_inventar;
create policy obiecte_inventar_admin_all on public.obiecte_inventar
  for all to authenticated using (is_staff_admin()) with check (is_staff_admin());
